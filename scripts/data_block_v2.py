# -*- coding: utf-8 -*-
"""共享数据区（三方必须完全一致）。

设计原则：
1. 列布局按用途分块，语义用例表里的公式只引用这里定义的单元格；
2. 全部用「数值」存放（日期用 Excel 序列号），避免三方对日期对象的处理差异污染结果；
3. 每块都留出「非退化」数据：成对的 x/y 有真实离散度，避免 CORREL 恒等于 1、STDEV 恒等于 0。
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))

# (cell, value) —— value 为 int/float/str，None 表示清空
CELLS = [
    # A1:A6 / B1:B6  y、x 两条数列（有真实离散度）
    ('A1', 1), ('A2', 2), ('A3', 3), ('A4', 4), ('A5', 5), ('A6', 6),
    ('B1', 2), ('B2', 4), ('B3', 5), ('B4', 4), ('B5', 5), ('B6', 7),
    # C1:C6  文本
    ('C1', 'abc'), ('C2', 'def'), ('C3', 'ghi'), ('C4', 'jkl'), ('C5', 'mno'), ('C6', 'pqr'),
    # D1:D6  小数
    ('D1', 0.5), ('D2', 1.5), ('D3', 2.5), ('D4', 3.5), ('D5', 4.5), ('D6', 5.5),
    # E1:E6  量级数
    ('E1', 10), ('E2', 20), ('E3', 30), ('E4', 40), ('E5', 50), ('E6', 60),
    # F1:F6  利率
    ('F1', 0.1), ('F2', 0.2), ('F3', 0.3), ('F4', 0.4), ('F5', 0.5), ('F6', 0.6),
    # H1:I4  带表头的键值表（查找/数据库函数）
    ('H1', 'k'), ('I1', 'v'),
    ('H2', 1), ('I2', 10),
    ('H3', 2), ('I3', 20),
    ('H4', 3), ('I4', 30),
    # J1     INDIRECT 用文本
    ('J1', 'IV'),
    # K1:K2  数据库条件（>1）；K3:K4 第二条条件（=2，供 DGET）
    ('K1', 'k'), ('K2', '>1'), ('K3', 'k'), ('K4', 2),
    # O1:O6  含重复值（MODE/UNIQUE 用）
    ('O1', 1), ('O2', 2), ('O3', 2), ('O4', 3), ('O5', 3), ('O6', 3),
    # P1:P5  现金流（IRR/MIRR/XIRR/XNPV）
    ('P1', -10000), ('P2', 3000), ('P3', 3000), ('P4', 3000), ('P5', 3000),
    # Q1:Q4  NPV 用正向现金流
    ('Q1', 3000), ('Q2', 3000), ('Q3', 3000), ('Q4', 3000),
    # R1:R5  与 P 配套的日期序列号（2020-01-01 起每年）
    ('R1', 43831), ('R2', 44197), ('R3', 44562), ('R4', 44927), ('R5', 45292),
    # U1:W3  3x3 可逆矩阵（MDETERM/MINVERSE/MMULT 用）
    ('U1', 1), ('V1', 2), ('W1', 3),
    ('U2', 4), ('V2', 5), ('W2', 6),
    ('U3', 7), ('V3', 8), ('W3', 10),
    # AK1:AL12  12 点时间序列（放远一点，避免与 Z 列公式的溢出区冲突）（FORECAST.ETS.CONFINT 需要足够周期）
    ('AK1', 1), ('AK2', 2), ('AK3', 3), ('AK4', 4), ('AK5', 5), ('AK6', 6),
    ('AK7', 7), ('AK8', 8), ('AK9', 9), ('AK10', 10), ('AK11', 11), ('AK12', 12),
    ('AL1', 3), ('AL2', 5), ('AL3', 4), ('AL4', 6), ('AL5', 5), ('AL6', 7),
    ('AL7', 6), ('AL8', 8), ('AL9', 7), ('AL10', 9), ('AL11', 8), ('AL12', 10),
    # X1:X6  概率列（合计 1，供 PROB 用）
    ('X1', 0.1), ('X2', 0.15), ('X3', 0.2), ('X4', 0.15), ('X5', 0.2), ('X6', 0.2),
]

# 公式型单元格：放进数据区，供 FORMULATEXT / ISFORMULA 引用
FORMULA_CELLS = [('S1', '=A1+1')]

# 供报告引用的可读说明
GROUP_NOTES = [
    ('A1:A6', '1,2,3,4,5,6 数列 y'),
    ('B1:B6', '2,4,5,4,5,7 数列 x'),
    ('C1:C6', '文本 abc/def/ghi/jkl/mno/pqr'),
    ('D1:D6', '小数 0.5~5.5'),
    ('E1:E6', '10~60'),
    ('F1:F6', '0.1~0.6 利率'),
    ('H1:I4', '带表头键值表 k/v'),
    ('J1', '文本 IV（INDIRECT）'),
    ('K1:K4', '数据库条件区'),
    ('O1:O6', '含重复值 1,2,2,3,3,3'),
    ('P1:P5 / Q1:Q4 / R1:R5', '现金流、正向现金流、配套日期序列号'),
    ('S1', '公式 =A1+1（FORMULATEXT/ISFORMULA）'),
    ('U1:W3', '3x3 矩阵'),
    ('X1:X6', '概率列（合计 1，PROB 用）'),
    ('AK1:AL12', '12 点时间序列（ETS 类需足够周期）'),
]

if __name__ == '__main__':
    out = {
        'cells': [{'cell': c, 'value': v} for c, v in CELLS],
        'formulaCells': [{'cell': c, 'formula': f} for c, f in FORMULA_CELLS],
        'groups': [{'range': r, 'note': n} for r, n in GROUP_NOTES],
    }
    p = os.path.join(HERE, 'data_block_v2.json')
    json.dump(out, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('saved', p, '| cells', len(CELLS), '+ formula', len(FORMULA_CELLS))
